// Writes plugin/Source/dsp/Params.gen.h from src/dsp/params.ts: the flat
// parameter list, the chip's constant tables and the factory presets, so the
// C++ engine and the host see exactly what the web version sees. Run after
// changing params.ts:
//
//   node scripts/gen-plugin.ts

import { writeFileSync } from 'node:fs';
import { PARAMS, PRESETS, CHANNELS, CLOCK_HZ, DUTY_VALUES, CHORD_SEMIS } from '../src/dsp/params.ts';

const out = 'plugin/Source/dsp/Params.gen.h';
const idx = new Map(PARAMS.map((p, i) => [p.id, i]));
const num = (x: number) => {
  const s = String(x);
  return /[.e]/.test(s) ? s : `${s}.0`;
};
const str = (s: string | undefined) => (s === undefined ? 'nullptr' : JSON.stringify(s));
const SCALE = { lin: 'Lin', log: 'Log', int: 'Int', enum: 'Enum', bool: 'Bool' } as const;
const TABS = ['wv', 'tvA', 'tvB', 'tp'];
const CHANNEL_KEYS = ['Level', 'Oct', 'Semi', 'Fine', 'Pan', 'Env', 'Atk', 'Dec', 'Sus', 'Rel', 'PTab'];

const L: string[] = [];
L.push('// Generated by scripts/gen-plugin.ts from src/dsp/params.ts. Do not edit.');
L.push('#pragma once');
L.push('');
L.push('namespace ftvector {');
L.push('');
L.push('enum class Scale { Lin, Log, Int, Enum, Bool };');
L.push('');
L.push('/** `tab` is the drawn table a cell belongs to (0 wave, 1 vol A, 2 vol B, 3 pitch; -1 none), `idx` its cell. */');
L.push('struct ParamDef {');
L.push('  const char* id; const char* name; const char* group;');
L.push('  double min, max, def; Scale scale; const char* unit;');
L.push('  const char* const* labels; int numLabels;');
L.push('  int tab, idx;');
L.push('};');
L.push('');
L.push('namespace P {');
L.push('enum : int {');
for (const p of PARAMS) L.push(`  ${p.id},`);
L.push('  COUNT');
L.push('};');
L.push('}');
L.push('');
L.push('constexpr int NUM_PARAMS = P::COUNT;');
L.push('');
PARAMS.forEach((p) => {
  if (p.labels) L.push(`inline constexpr const char* LABELS_${p.id}[] = { ${p.labels.map((l) => JSON.stringify(l)).join(', ')} };`);
});
L.push('');
L.push('inline constexpr ParamDef PARAMS[NUM_PARAMS] = {');
for (const p of PARAMS) {
  const labels = p.labels ? `LABELS_${p.id}, ${p.labels.length}` : 'nullptr, 0';
  const tab = p.tab === undefined ? -1 : TABS.indexOf(p.tab);
  if (p.tab !== undefined && tab < 0) throw new Error(`param ${p.id}: unknown table ${p.tab}`);
  L.push(`  { ${str(p.id)}, ${str(p.name)}, ${str(p.group)}, ${num(p.min)}, ${num(p.max)}, ${num(p.def)}, Scale::${SCALE[p.scale]}, ${str(p.unit)}, ${labels}, ${tab}, ${p.idx ?? -1} },`);
}
L.push('};');
L.push('');
L.push('/** Per channel (pulse 1, pulse 2, wave, noise, fm, pd), the index of each of its common parameters. */');
L.push('struct ChannelIds { int level, oct, semi, fine, pan, env, atk, dec, sus, rel, ptab; };');
L.push('inline constexpr ChannelIds CHANNEL_IDS[6] = {');
for (const c of CHANNELS) L.push(`  { ${CHANNEL_KEYS.map((k) => `P::${c.pre}${k}`).join(', ')} },`);
L.push('};');
L.push('');
L.push(`inline constexpr double CLOCK_HZ[] = { ${CLOCK_HZ.map(num).join(', ')} };`);
L.push(`inline constexpr double DUTY_VALUES[] = { ${DUTY_VALUES.map(num).join(', ')} };`);
const maxChord = Math.max(...CHORD_SEMIS.map((c) => c.length));
L.push(`constexpr int NUM_CHORDS = ${CHORD_SEMIS.length};`);
L.push(`inline constexpr int CHORD_LEN[NUM_CHORDS] = { ${CHORD_SEMIS.map((c) => c.length).join(', ')} };`);
L.push(`inline constexpr int CHORD_SEMIS[NUM_CHORDS][${maxChord}] = { ${CHORD_SEMIS.map((c) => `{ ${[...c, ...Array(maxChord - c.length).fill(0)].join(', ')} }`).join(', ')} };`);
L.push('');
L.push('struct PresetValue { int id; double value; };');
L.push('struct Preset { const char* name; const char* tag; const PresetValue* values; int count; };');
L.push('');
PRESETS.forEach((pr, i) => {
  const vals = Object.entries(pr.values).map(([id, v]) => {
    const k = idx.get(id);
    if (k === undefined) throw new Error(`preset "${pr.name}": unknown param ${id}`);
    return `{ P::${id}, ${num(v!)} }`;
  });
  // an empty preset (init) has no array: C++ has no zero-length ones
  if (vals.length) L.push(`inline constexpr PresetValue PRESET_${i}[] = { ${vals.join(', ')} };`);
});
L.push('');
L.push(`constexpr int NUM_PRESETS = ${PRESETS.length};`);
L.push('inline constexpr Preset PRESETS[NUM_PRESETS] = {');
PRESETS.forEach((pr, i) => L.push(`  { ${str(pr.name)}, ${str(pr.tag)}, ${Object.keys(pr.values).length ? `PRESET_${i}` : 'nullptr'}, ${Object.keys(pr.values).length} },`));
L.push('};');
L.push('');
L.push('} // namespace ftvector');
L.push('');

writeFileSync(out, L.join('\n'));
console.log(`wrote ${out}: ${PARAMS.length} params, ${PRESETS.length} presets`);
